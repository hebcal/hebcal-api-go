// Prints internal/service/ical/omer.go: the Omer count in English and Hebrew
// and the sefira in Hebrew for each of the 49 days, as @hebcal/core writes them.
//
//   node tools/dump-omer.mjs > internal/service/ical/omer.go
//
// hebcal-go's OmerEvent words the Hebrew without the meteg and dagesh
// @hebcal/core writes ("הַיוֹם ... לָעוֹמֶר" for "הַיּוֹם ... לָעֽוֹמֶר"), so the
// feeds take the strings from @hebcal/core until hebcal-go is fixed.
import {importFromWeb} from './hebcalweb.mjs';

const {HDate, OmerEvent} = await importFromWeb('node_modules/@hebcal/core/dist/esm/index.js');

const lines = [];
for (let day = 1; day <= 49; day++) {
  const ev = new OmerEvent(new HDate(15 + day, 'Nisan', 5787), day);
  lines.push(`\t{${JSON.stringify(ev.getTodayIs('en'))}, ${JSON.stringify(ev.getTodayIs('he'))}, ${JSON.stringify(ev.sefira('he'))}},`);
}
console.log(`// Code generated by tools/dump-omer.mjs; DO NOT EDIT.

package ical

// omerText is each Omer day's count in English and in Hebrew with nikud, and
// its sefira in Hebrew, indexed by day - 1.
var omerText = [49]struct{ todayIsEn, todayIsHe, sefiraHe string }{
${lines.join('\n')}
}`);
