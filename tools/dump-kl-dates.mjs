// Writes internal/service/ical/kldates.go: how Intl formats the dates in a
// Kiddush Levana description for each locale a calendar can be in, since Go
// has no CLDR to ask. Each locale's weekday and month names and the order
// they come in, taken from
//
//   new Intl.DateTimeFormat(locale, {weekday: 'short', day: 'numeric',
//                                    month: 'short', year: 'numeric'})
//
//   node tools/dump-kl-dates.mjs > internal/service/ical/kldates.go
const locales = {
  de: 'de', es: 'es', fi: 'fi', fr: 'fr', he: 'he-IL', hu: 'hu', nl: 'nl',
  pl: 'pl', pt: 'pt', ro: 'ro', ru: 'ru', uk: 'uk',
};

const opts = {weekday: 'short', day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC'};
const q = (s) => JSON.stringify(s);
const out = [];
out.push(`// Code generated by tools/dump-kl-dates.mjs; DO NOT EDIT.

package ical

// klDateFormat is how one language writes the short date in a Kiddush Levana
// description: its weekday and month names, and the pattern they go in.
type klDateFormat struct {
	Weekdays [7]string // Sunday first
	Months   [12]string
	// Pattern places {w}eekday, {d}ay, {m}onth and {y}ear.
	Pattern string
}

// klDateFormats is keyed by the resolved locale name.
var klDateFormats = map[string]klDateFormat{`);
for (const [name, tag] of Object.entries(locales)) {
  const f = new Intl.DateTimeFormat(tag, opts);
  const parts = (d) => f.formatToParts(new Date(Date.UTC(2025, d[0], d[1])));
  // Sunday 2025-12-21 on: the weekday names; the 15th of each month.
  const weekdays = [];
  for (let i = 0; i < 7; i++) {
    weekdays.push(parts([11, 21 + i]).find((p) => p.type === 'weekday').value);
  }
  const months = [];
  for (let m = 0; m < 12; m++) {
    months.push(parts([m, 15]).find((p) => p.type === 'month').value);
  }
  const pattern = parts([11, 22]).map((p) => {
    switch (p.type) {
      case 'weekday': return '{w}';
      case 'day': return '{d}';
      case 'month': return '{m}';
      case 'year': return '{y}';
      // format() writes a plain space where formatToParts() has a narrow
      // no-break one.
      case 'literal': return p.value.replaceAll('\u202f', ' ');
      default: throw new Error(`${name}: unexpected ${p.type}`);
    }
  }).join('');
  // The pattern has to give back what format() gives, for every date.
  for (let m = 0; m < 12; m++) {
    for (const day of [1, 9, 22, 28]) {
      const dt = new Date(Date.UTC(2025, m, day));
      const got = pattern.replace('{w}', weekdays[dt.getUTCDay()]).replace('{d}', day)
          .replace('{m}', months[m]).replace('{y}', 2025);
      if (got !== f.format(dt)) {
        throw new Error(`${name}: ${JSON.stringify(got)} != ${JSON.stringify(f.format(dt))}`);
      }
    }
  }
  out.push(`\t${q(name)}: {
		Weekdays: [7]string{${weekdays.map(q).join(', ')}},
		Months:   [12]string{${months.map(q).join(', ')}},
		Pattern:  ${q(pattern)},
	},`);
}
out.push('}');
console.log(out.join('\n'));
